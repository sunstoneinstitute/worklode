package cmd

import (
	"fmt"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// renderCommandReference walks root's command tree and renders it as the
// markdown consumed by plugins/claude/lode/skills/worklode/references/commands.md
// (kept fresh by TestCommandReference in commandref_test.go). One H2 per
// top-level command, naming its own flags (if it takes any directly, e.g.
// `lode install`) plus one bullet per descendant, depth-first and
// path-qualified (`lode task claim`, not just `claim`). Every command also
// accepts `--json` and `--help`; both are omitted throughout as implied.
//
// The 061 §1 L9 shortcuts get one line up front rather than an H2 of their
// own: each is a second instance of a command already documented under its
// real parent, so an H2 would duplicate that entry.
func renderCommandReference(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString("# lode command reference\n\n")
	b.WriteString("Generated by `go test ./internal/cmd -run TestCommandReference " +
		"-update-command-ref` — do not hand-edit. Every command also accepts " +
		"`--json`, omitted below as implied. Add `--help` to any command below " +
		"for flag defaults and full descriptions.\n\n")

	if len(shortcuts) > 0 {
		var pairs []string
		for _, s := range shortcuts {
			pairs = append(pairs, fmt.Sprintf("`lode %s` runs `lode %s`",
				s.target[len(s.target)-1], strings.Join(s.target, " ")))
		}
		sort.Strings(pairs)
		fmt.Fprintf(&b, "Shortcuts: %s.\n\n", strings.Join(pairs, "; "))
	}

	for _, top := range sortedVisibleCommands(root) {
		if top.GroupID == shortcutGroupID {
			continue // documented under its real parent, plus the line above
		}
		var section strings.Builder
		fmt.Fprintf(&section, "## `lode %s` — %s\n\n", top.Name(), top.Short)
		if flags := localFlagNames(top); len(flags) > 0 {
			fmt.Fprintf(&section, "Flags: %s\n\n", strings.Join(flags, ", "))
		}
		renderCommandChildren(&section, top, top.Name())
		b.WriteString(strings.TrimRight(section.String(), "\n") + "\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// renderCommandChildren renders one bullet per child of c, depth-first,
// path-qualified against path.
func renderCommandChildren(b *strings.Builder, c *cobra.Command, path string) {
	for _, child := range sortedVisibleCommands(c) {
		childPath := path + " " + child.Name()
		fmt.Fprintf(b, "- `lode %s`", childPath)
		if flags := localFlagNames(child); len(flags) > 0 {
			fmt.Fprintf(b, " — %s\n  Flags: %s\n", child.Short, strings.Join(flags, ", "))
		} else {
			fmt.Fprintf(b, " — %s\n", child.Short)
		}
		renderCommandChildren(b, child, childPath)
	}
}

// sortedVisibleCommands excludes cobra's auto-added help/completion commands
// and anything explicitly hidden, then sorts by name for a stable diff.
func sortedVisibleCommands(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, sub := range c.Commands() {
		if sub.Hidden || sub.Name() == "help" || sub.Name() == "completion" {
			continue
		}
		out = append(out, sub)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}

// localFlagNames lists c's own flags (never --json, inherited from root, and
// never --help, which cobra adds to every command) as "--name", sorted.
func localFlagNames(c *cobra.Command) []string {
	var names []string
	c.LocalNonPersistentFlags().VisitAll(func(f *pflag.Flag) {
		if f.Name == "help" {
			return
		}
		names = append(names, "--"+f.Name)
	})
	sort.Strings(names)
	return names
}
